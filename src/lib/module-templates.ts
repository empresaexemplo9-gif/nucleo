/** Modelos prontos de módulos de controle interno e pacotes por segmento. */

export type TplField = {
  key: string;
  label: string;
  type: string;
  options?: string[];
  required?: boolean;
  list?: boolean;
  due?: boolean;
  amount?: boolean;
  /** RECORD: chave do modelo do módulo vinculado */
  target?: string;
  /** FORMULA: expressão com {campos} e formato do resultado */
  formula?: string;
  format?: "NUMBER" | "CURRENCY" | "PERCENT";
  /** Lista que define a repetição do registro ao ser concluído */
  recur?: boolean;
};
export type TplStatus = { name: string; color: string; final?: boolean };
export type ModuleTemplate = {
  key: string;
  name: string;
  singular: string;
  description: string;
  icon: string;
  color: string;
  prefix: string;
  fields: TplField[];
  statuses: TplStatus[];
  /** Perfil mínimo para ver/editar (ex.: prontuário só para quem atende) */
  minRoleView?: "VIEWER" | "SALES" | "MANAGER" | "ADMIN";
  minRoleEdit?: "SALES" | "MANAGER" | "ADMIN";
  /** Grupo no menu lateral */
  group?: string;
};

