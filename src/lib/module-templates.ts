/** Opções gravadas no campo conforme o tipo (vínculo e fórmula usam `options` para a configuração). */
export function fieldOptions(f: TplField) {
  if (f.type === "RECORD") return [`tpl:${f.target ?? ""}`];
  if (f.type === "FORMULA") return [f.formula ?? "", f.format ?? "NUMBER"];
  return f.options ?? [];
}

