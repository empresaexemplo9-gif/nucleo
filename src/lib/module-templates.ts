/** Mapeia o segmento escolhido no cadastro para um pacote. */
export function packForSegment(segment?: string | null) {
  const s = (segment ?? "").toLowerCase();
  const pick = (k: string) => SEGMENT_PACKS.find((p) => p.key === k)!;
  if (/imobili|corretor de im|im[oó]ve/.test(s)) return pick("imobiliaria");
  if (/constru|arquit|engenh|obra/.test(s)) return pick("construcao");
  if (/agro|fazend|pecu/.test(s)) return pick("agro");
  if (/beleza|est[eé]tic|sal[aã]o|barbear|spa/.test(s)) return pick("beleza");
  if (/academ|fitness|est[uú]dio|pilates|crossfit/.test(s)) return pick("academia");
  if (/sa[uú]de|cl[ií]nic|consult[oó]rio|odonto|fisio|psic/.test(s)) return pick("saude");
  if (/educa|escola|curso/.test(s)) return pick("educacao");
  if (/jur[ií]d|advoc/.test(s)) return pick("juridico");
  if (/seguro/.test(s)) return pick("seguros");
  if (/roupa|moda|vestu[aá]rio|acess[oó]rio|boutique|confec|cal[cç]ado|bijuter/.test(s)) return pick("moda");
  if (/varejo|com[eé]rcio|loja/.test(s)) return pick("varejo");
  if (/ind[uú]str|f[aá]brica/.test(s)) return pick("industria");
  if (/software|saas|tecnolog/.test(s)) return pick("tecnologia");
  if (/ag[eê]ncia|marketing|publicidade/.test(s)) return pick("agencia");
  if (/consultor/.test(s)) return pick("consultoria");
  if (/servi[cç]|assist[eê]ncia|manuten|financeiro/.test(s)) return pick("servicos");
  return pick("geral");
}

